// Writes THIRD_PARTY_NOTICES.md from package.json and the installed packages: every direct dependency with its
// version and licence. Run it after changing dependencies:  node scripts/generate-notice.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const shipped = new Set(['better-sqlite3', 'yauzl', 'yazl', 'react', 'react-dom', 'react-router-dom', 'recharts', '@dnd-kit/core', '@dnd-kit/sortable', '@dnd-kit/utilities', 'tailwindcss', 'electron'])

const rows = []
for (const [name, range] of Object.entries({ ...pkg.dependencies, ...pkg.devDependencies })) {
  const p = JSON.parse(readFileSync(join(root, 'node_modules', name, 'package.json'), 'utf8'))
  const license = typeof p.license === 'string' ? p.license : (p.license?.type ?? 'see package')
  const home = p.homepage ?? (typeof p.repository === 'string' ? p.repository : (p.repository?.url ?? '')).replace(/^git\+/, '').replace(/\.git$/, '')
  rows.push({ name, version: p.version, range, license, home, shipped: shipped.has(name) })
}
rows.sort((a, b) => Number(b.shipped) - Number(a.shipped) || a.name.localeCompare(b.name))

const table = (list) => ['| Package | Version | Licence | Link |', '| --- | --- | --- | --- |', ...list.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.home} |`)].join('\n')
const md = `# Third-party notices

Generated by \`scripts/generate-notice.mjs\` from \`package.json\`. Do not edit by hand.

## Included in the application

These packages end up inside the installed app (Electron itself, and the libraries bundled into it).

${table(rows.filter((r) => r.shipped))}

Electron bundles Chromium and Node.js. Their licences (and those of the libraries inside them) are listed in the
\`LICENSES.chromium.html\` file that Electron places next to the application, and in the installed app's folder.

## Used only to build and test

${table(rows.filter((r) => !r.shipped))}
`
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), md)
console.log(`Wrote THIRD_PARTY_NOTICES.md (${rows.length} packages)`)
